def _fill(kind: str, name: str, hook: str, spots: list[str], caution: str) -> dict[str, list[str]]:
    spot0 = spots[0]
    spot1 = spots[1] if len(spots) > 1 else spots[0]
    values = {
        "name": name,
        "hook": hook,
        "spot0": spot0,
        "spot1": spot1,
        "spots": "、".join(spots),
        "caution": caution,
    }
    guide = {}
    for key, lines in TEMPLATES[kind].items():
        mapped = {
            "finished": "finished_points",
            "scouting": "scouting",
            "pre": "pre",
            "post": "post",
            "lighting": "lighting",
            "posing": "posing",
        }[key]
        guide[mapped] = [line.format(**values) for line in lines]
    return guide


def landscape_subject(row: tuple) -> dict:
    slug, name, kind, hook, spots, caution, geo, axes, verify = row
    examples = []
    for index, spot in enumerate(spots):
        examples.append(
            {
                "name": spot,
                "geo_text": geo,
                "note": f"{name}的同页机位，不单独成题材。只记公开区域。",
                "verify_status": verify,
            }
        )
    aliases = [hook]
    if spots[0] not in aliases:
        aliases.append(spots[0])
    if slug == "huangshan":
        aliases.append("黄山云海")
    return {
        "slug": slug,
        "name": name,
        "channel": "landscape",
        "type": "location",
        "tagline": f"{name}：先把{hook}拍清楚，机位都写在这一页。",
        "aliases": aliases,
        "guide": _fill(kind, name, hook, spots, caution),
        "examples": examples,
        "geo_text": geo,
        "safety_notes": caution,
        "condition_axes": axes,
    }


